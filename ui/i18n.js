let LANG = "es";

/** Texto en el idioma actual. Si falta, se usa el español; si tampoco existe, la clave. */
function t(key, vars) {
  const text = I18N[LANG][key] ?? I18N.es[key] ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m)) : text;
}

/** Singular o plural según n: tn("history.recordings", 3) → "3 grabaciones". */
const tn = (key, n, vars = {}) => t(`${key}.${n === 1 ? "one" : "other"}`, { n, ...vars });

const locale = () => LOCALES[LANG];

/** Reemplaza el primer texto propio del elemento (no el de sus iconos o hijos). */
function setOwnText(el, text) {
  const node = [...el.childNodes].find((n) => n.nodeType === 3 && n.textContent.trim());
  if (!node) { if (!el.children.length) el.textContent = text; else el.append(text); return; }
  node.textContent = text + (/\s$/.test(node.textContent) ? " " : "");
}

/** Traduce los elementos marcados con data-i18n* dentro de root. */
function applyI18n(root = document) {
  for (const el of root.querySelectorAll("[data-i18n]")) setOwnText(el, t(el.dataset.i18n));
  for (const el of root.querySelectorAll("[data-i18n-title]")) {
    el.title = t(el.dataset.i18nTitle);
    el.setAttribute("aria-label", el.title);
  }
  for (const el of root.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.dataset.i18nAria));
  if (root.documentElement) root.documentElement.lang = LANG;
}

/** Cambia el idioma y vuelve a traducir los textos fijos. Devuelve el idioma efectivo. */
function setLang(lang) {
  LANG = LANGS.includes(lang) ? lang : "es";
  if (typeof document !== "undefined") applyI18n(document);
  return LANG;
}

if (typeof module !== "undefined") {
  module.exports = { LANGS, LOCALES, I18N, t, tn, setLang, locale, getLang: () => LANG };
}
